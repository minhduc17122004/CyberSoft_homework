void main() {
  // =========================
  // Bài 1: == và !=
  // =========================
  int a = 10;
  int b = 20;

  print("===== Bài 1 =====");
  print("a == b: ${a == b}");
  print("a != b: ${a != b}");

  // =========================
  // Bài 2: > và <
  // =========================
  int x = 15;
  int y = 8;

  print("\n===== Bài 2 =====");
  print("x > y: ${x > y}");
  print("x < y: ${x < y}");

  // =========================
  // Bài 3: >= và <=
  // =========================
  double p = 5.5;
  double q = 5.5;

  print("\n===== Bài 3 =====");
  print("p >= q: ${p >= q}");
  print("p <= q: ${p <= q}");
}
